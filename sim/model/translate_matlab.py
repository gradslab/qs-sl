"""Translate the Maple-generated MATLAB expressions of the controller into Python.

The files matlab/h1_.m, h2_.m, h3_.m and b_.m hold the outputs, their time derivatives along the
closed loop up to order five, the gradients of the outputs and the sixth-order drift terms b1 and b3.
They were produced by Maple from the model in coordinates. This script rewrites them as one Python
function in qsf_gen.py. Nothing is simplified or reordered, so the Python code evaluates the same
expressions as the MATLAB code.

    python3 model/translate_matlab.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
MATLAB = os.path.abspath(os.path.join(HERE, '..', '..', 'matlab'))
OUT = os.path.join(HERE, 'qsf_gen.py')

ARGS = ['p__1', 'p__2', 'p__3', 'v__1', 'v__2', 'v__3', 'alpha', 'beta', 'gamma__alpha', 'gamma__beta',
        'theta', 'phi', 'psi', 'Omega__1', 'Omega__2', 'Omega__3']
PARAMS = ['g', 'L', 'm__q', 'm__p', 'r1', 'r2', 'vd', 'k__21', 'k__22', 'J__1', 'J__2', 'J__3', 'c__1', 'c__2', 'k__Om']
RESULTS = ['h1', 'h1__dt', 'h1__ddt', 'h1__dddt', 'h1__ddddt', 'h1__dddddt',
           'h2', 'h2__dt',
           'h3', 'h3__dt', 'h3__ddt', 'h3__dddt', 'h3__ddddt', 'h3__dddddt',
           'b1', 'b3']
# the three gradient rows are written by hand (MATLAB row-vector syntax)
GRADIENTS = {'dh_1': '(2 * p__1, 2 * p__2, 0.0)',
             'dh_2': '(0.0, 0.0, 1.0)',
             'dh_3': '(-p__2 / (p__1 ** 2 + p__2 ** 2), p__1 / (p__1 ** 2 + p__2 ** 2), 0.0)'}


def statements(path):
    out = []
    for line in open(path, encoding='utf-8', errors='replace'):
        line = line.replace('\r', '').strip()
        if not line or line.startswith('%'):
            continue
        if '%' in line:
            raise ValueError(f'unexpected comment in {path}: {line[:60]}')
        if not line.endswith(';'):
            raise ValueError(f'statement without terminator in {path}: {line[:60]}')
        name, expr = line[:-1].split('=', 1)
        out.append((name.strip(), expr.strip()))
    return out


def to_python(expr):
    e = expr.replace('^', '**')
    if re.search(r'\*\*\s*[\w.]+\s*\*\*', e):
        raise ValueError('chained power needs parentheses: ' + e[:80])
    if "'" in e or '.*' in e or './' in e or '[' in e:
        raise ValueError('matrix syntax: ' + e[:80])
    return e


def main():
    lines = []
    for f in ('h1_.m', 'h2_.m', 'h3_.m', 'b_.m'):
        for name, expr in statements(os.path.join(MATLAB, f)):
            if name in GRADIENTS:
                continue
            lines.append(f'    {name} = {to_python(expr)}')
    names = {l.split('=')[0].strip() for l in lines}
    missing = [r for r in RESULTS if r not in names]
    if missing:
        raise ValueError('missing results: ' + ', '.join(missing))
    header = ['"""Generated by translate_matlab.py from matlab/h1_.m, h2_.m, h3_.m and b_.m. Do not edit."""',
              'from math import sin, cos, tan, atan2', '', '',
              'def sec(x):', '    return 1.0 / cos(x)', '', '',
              'def qsf_terms(' + ', '.join(ARGS) + ', ' + ', '.join(PARAMS) + '):',
              '    """outputs, their derivatives along the closed loop and the sixth-order drift terms"""']
    footer = ['    dh_1 = ' + GRADIENTS['dh_1'], '    dh_2 = ' + GRADIENTS['dh_2'], '    dh_3 = ' + GRADIENTS['dh_3'],
              '    return dict(' + ', '.join(f'{r}={r}' for r in RESULTS + ['dh_1', 'dh_2', 'dh_3']) + ')', '']
    open(OUT, 'w').write('\n'.join(header + lines + footer))
    print(f'wrote {OUT}: {len(lines)} statements')


if __name__ == '__main__':
    main()
